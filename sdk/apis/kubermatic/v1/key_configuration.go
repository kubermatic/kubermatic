package v1

// KeyAlgorithm is the public-key algorithm used for keys generated by KKP
// for a user cluster.
//
// +kubebuilder:validation:Enum=RSA;ECDSA
type KeyAlgorithm string

const (
	// KeyAlgorithmRSA selects the RSA algorithm; the modulus size is taken
	// from KeySpec.RSAKeySize.
	KeyAlgorithmRSA KeyAlgorithm = "RSA"
	// KeyAlgorithmECDSA selects the ECDSA algorithm; the curve is taken from
	// KeySpec.ECDSACurve.
	KeyAlgorithmECDSA KeyAlgorithm = "ECDSA"
)

// ECDSACurve is the elliptic curve used when KeyAlgorithm is ECDSA.
//
// P-521 is deliberately not offered: client support for it is uneven and it
// satisfies no policy that P-384 does not.
//
// +kubebuilder:validation:Enum=P256;P384
type ECDSACurve string

const (
	ECDSACurveP256 ECDSACurve = "P256"
	ECDSACurveP384 ECDSACurve = "P384"
)

// DefaultRSAKeySize is the RSA modulus size KKP used for all generated key
// material before KeyConfiguration existed, and the size that continues to be
// used whenever no explicit configuration applies.
const DefaultRSAKeySize int32 = 2048

// KeySpec configures the algorithm and size of a generated private key.
//
// A nil KeySpec, or one with an empty Algorithm, means "use the legacy default
// of RSA-2048". That is the effective value for every cluster created before
// the KeyConfiguration field existed.
type KeySpec struct {
	// Algorithm is the public-key algorithm. Empty means RSA.
	// +optional
	Algorithm KeyAlgorithm `json:"algorithm,omitempty"`

	// RSAKeySize is the RSA modulus size in bits. Only valid when Algorithm
	// is RSA or empty. Empty means the legacy default of 2048.
	// +kubebuilder:validation:Enum=2048;3072;4096
	// +optional
	RSAKeySize int32 `json:"rsaKeySize,omitempty"`

	// ECDSACurve is the elliptic curve. Only valid when Algorithm is ECDSA.
	// Empty means P256.
	// +optional
	ECDSACurve ECDSACurve `json:"ecdsaCurve,omitempty"`
}

// KeyConfiguration groups the key settings for the material KKP generates for
// a user cluster.
//
// Note that this does not cover key material that does not belong to a single
// user cluster, such as the KKP webhook CA or the VPA admission certificate;
// those remain RSA-2048.
//
// The value configured globally in the KubermaticConfiguration is copied into
// ClusterSpec.KeyConfiguration when a cluster is created, and is immutable from
// then on. Reconcilers only ever read the copy stored on the Cluster, so
// changing the global default never affects clusters that already exist.
//
// There is deliberately no way to change this for a cluster that already exists.
// Rotating key material in place means re-issuing every leaf certificate, every
// internal kubeconfig, every kubelet client certificate and every webhook CA
// bundle while keeping the control plane reachable, which KKP does not implement
// yet. Recreating the cluster is currently the only way to change its key
// material.
type KeyConfiguration struct {
	// ServiceAccountKey configures the user-cluster service-account token
	// signing key. This key is consumed by systems outside the cluster when
	// they validate JWTs, so its algorithm and size are externally visible.
	// +optional
	ServiceAccountKey *KeySpec `json:"serviceAccountKey,omitempty"`

	// Certificates configures the cluster-internal CAs and leaf certificates
	// (etcd, apiserver, front-proxy and the component clients).
	// +optional
	Certificates *KeySpec `json:"certificates,omitempty"`
}
