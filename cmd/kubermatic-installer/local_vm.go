const (
	limaVMNamePrefix    = "kkp-"
	limaRegistryPort    = 5000
	vmKindAPIserverPort = 36443
	vmKindVersion       = "v0.27.0"
	vmRemoteDir         = "/tmp/kkp-local"
)

type limaVM struct {
	instance string
	cluster  string
	ip       string
}

func limaVMName(clusterName string) string {
	return limaVMNamePrefix + clusterName
}

// limaVMTemplate renders the lima instance template for a local kind VM.
// The VM uses the shared lima network so its IP is directly reachable
// from the host (the printed login URL opens in a browser). The in-VM
// registry, the kind apiserver and the four KKP host ports are
// additionally forwarded 1:1 between host and guest, so the same port
// numbers work on both sides.
func limaVMTemplate(clusterName string, cpus, memory, disk int, hostPorts map[string]int) string {
	ports := defaultLocalHostPorts()
	for key, value := range hostPorts {
		ports[key] = value
	}

	forwards := ""
	for _, forward := range []struct {
		port    int
		comment string
	}{
		{limaRegistryPort, "local container registry"},
		{vmKindAPIserverPort, "kind apiserver"},
		{ports["http"], "envoy gateway http"},
		{ports["https"], "envoy gateway https"},
		{ports["apiserver"], "nodeport-proxy apiserver tunnel"},
		{ports["tunnel"], "nodeport-proxy tunnel listener"},
	} {
		forwards += fmt.Sprintf("# %s\n- guestPort: %d\n  hostPort: %d\n", forward.comment, forward.port, forward.port)
	}

	return fmt.Sprintf(`# generated by kubermatic-installer local kind --vm
# instance: %s (reuse an existing VM with: limactl start %s)
images:
- location: "https://cloud-images.ubuntu.com/noble/current/noble-server-cloudimg-amd64.img"
  arch: "x86_64"
- location: "https://cloud-images.ubuntu.com/noble/current/noble-server-cloudimg-arm64.img"
  arch: "aarch64"
cpus: %d
memory: "%dGiB"
disk: "%dGiB"
networks:
- lima: shared
portForwards:
%s`, limaVMName(clusterName), limaVMName(clusterName), cpus, memory, disk, forwards)
}

func limaCommand(ctx context.Context, args ...string) *exec.Cmd {
	return exec.CommandContext(ctx, "limactl", append([]string{"--tty=false"}, args...)...)
}

func (vm *limaVM) shell(ctx context.Context, args ...string) *exec.Cmd {
	return limaCommand(ctx, append([]string{"shell", vm.instance, "--"}, args...)...)
}

func limaVMExists(ctx context.Context, instance string) bool {
	out, err := limaCommand(ctx, "list", "--quiet", instance).Output()
	if err != nil {
		return false
	}
	for _, line := range strings.Fields(string(out)) {
		if line == instance {
			return true
		}
	}
	return false
}

func startLimaVM(ctx context.Context, logger *logrus.Logger, opt *LocalOptions) (*limaVM, error) {
	instance := limaVMName(opt.ClusterName)

	if limaVMExists(ctx, instance) {
		logger.Infof("Lima VM %q already exists, reusing it (--vm-cpus, --vm-memory, --vm-disk and --host-ports changes are ignored)", instance)
		logger.Infof("Starting lima VM %q…", instance)
		if out, err := limaCommand(ctx, "start", instance).CombinedOutput(); err != nil {
			return nil, fmt.Errorf("failed to start lima VM %q: %w\n%s", instance, err, string(out))
		}
	} else {
		templateDir, err := os.MkdirTemp("", "kkp-lima-")
		if err != nil {
			return nil, fmt.Errorf("failed to create temporary directory for the lima template: %w", err)
		}
		defer os.RemoveAll(templateDir)

		template := filepath.Join(templateDir, "lima-vm.yaml")
		if err := os.WriteFile(template, []byte(limaVMTemplate(opt.ClusterName, opt.VMCPUs, opt.VMMemory, opt.VMDisk, opt.HostPorts)), 0644); err != nil {
			return nil, fmt.Errorf("failed to write lima template: %w", err)
		}

		logger.Infof("Creating lima VM %q (%d CPUs, %d GiB memory, %d GiB disk)…", instance, opt.VMCPUs, opt.VMMemory, opt.VMDisk)
		if out, err := limaCommand(ctx, "start", "--name", instance, template).CombinedOutput(); err != nil {
			return nil, fmt.Errorf("failed to create lima VM %q: %w\n%s", instance, err, string(out))
		}
	}

	return &limaVM{
		instance: instance,
		cluster:  opt.ClusterName,
	}, nil
}

func bootstrapLimaVM(ctx context.Context, logger *logrus.Logger, vm *limaVM) error {
	script := fmt.Sprintf(`set -euo pipefail

if ! command -v docker >/dev/null 2>&1; then
  echo "installing docker"
  curl -fsSL https://get.docker.com | sudo sh
fi
sudo systemctl enable --now docker

if ! id -nG "$USER" | grep -qw docker; then
  sudo usermod -aG docker "$USER"
fi

case "$(uname -m)" in
  aarch64) ARCH=arm64 ;;
  *)       ARCH=amd64 ;;
esac

if ! command -v kind >/dev/null 2>&1; then
  echo "installing kind %[2]s"
  curl -fsSLo /tmp/kind "https://kind.sigs.k8s.io/dl/%[2]s/kind-linux-${ARCH}"
  sudo install -m 0755 /tmp/kind /usr/local/bin/kind
fi

if ! command -v kubectl >/dev/null 2>&1; then
  echo "installing kubectl"
  KUBECTL_VERSION="$(curl -fsSL https://dl.k8s.io/release/stable.txt)"
  curl -fsSLo /tmp/kubectl "https://dl.k8s.io/release/${KUBECTL_VERSION}/bin/linux/${ARCH}/kubectl"
  sudo install -m 0755 /tmp/kubectl /usr/local/bin/kubectl
fi

if ! sudo docker ps -a --format '{{.Names}}' | grep -qx '%[1]s-registry'; then
  echo "starting %[1]s-registry container"
  sudo docker run -d --name '%[1]s-registry' -p %[3]d:%[3]d registry:2
elif ! sudo docker ps --format '{{.Names}}' | grep -qx '%[1]s-registry'; then
  sudo docker start '%[1]s-registry'
fi

echo "bootstrap complete"
`, vm.cluster, vmKindVersion, limaRegistryPort)

	logger.Infof("Bootstrapping docker, kind, kubectl and the registry inside the VM (idempotent)…")
	if out, err := vm.shell(ctx, "bash", "-c", script).CombinedOutput(); err != nil {
		return fmt.Errorf("failed to bootstrap the lima VM: %w\n%s", err, string(out))
	}

	if out, err := vm.shell(ctx, "kind", "version").CombinedOutput(); err != nil {
		return fmt.Errorf("failed to determine 'kind' version inside the VM: %w\n%s", err, string(out))
	} else {
		submatch := regexp.MustCompile(`.* v([^ ]*) .*`).FindStringSubmatch(string(out))
		if len(submatch) != 2 {
			return fmt.Errorf("failed to parse 'kind' version inside the VM, requires at least %v: %v", minSupportedKindVersion, string(out))
		}
		kindVersion, err := semver.NewSemver(submatch[1])
		if err != nil {
			return fmt.Errorf("failed to process 'kind' semver %q inside the VM, requires at least %v: %v", submatch[1], minSupportedKindVersion, string(out))
		}
		if kindVersion.LessThan(minSupportedKindVersion) {
			return fmt.Errorf("please update 'kind' %v inside the VM, requires at least %v", kindVersion, minSupportedKindVersion)
		}
	}

	return nil
}

func limaVMIP(ctx context.Context, logger *logrus.Logger, vm *limaVM) (string, error) {
	if out, err := limaCommand(ctx, "list", "--json", vm.instance).Output(); err == nil {
		if ip := limaIPFromJSON(out); ip != "" {
			return ip, nil
		}
		logger.Info("could not determine the VM IP from `limactl list --json`, falling back to hostname -I")
	} else {
		logger.Warnf("failed to list the lima VM as JSON: %v", err)
	}

	if out, err := vm.shell(ctx, "sh", "-c", "ip route get 1.1.1.1 2>/dev/null | grep -o 'src [0-9.]*' | cut -d' ' -f2").Output(); err == nil {
		if ip := strings.TrimSpace(string(out)); net.ParseIP(ip) != nil {
			return ip, nil
		}
	}

	if out, err := vm.shell(ctx, "sh", "-c", "hostname -I | cut -d' ' -f1").Output(); err == nil {
		if ip := strings.TrimSpace(string(out)); net.ParseIP(ip) != nil {
			return ip, nil
		}
	}

	return "", fmt.Errorf("failed to determine the IP of lima VM %q", vm.instance)
}

// limaIPFromJSON extracts the guest IP from `limactl list --json` output,
// tolerating the different shapes (single object, array or JSON lines) and
// field naming across limactl versions.
func limaIPFromJSON(data []byte) string {
	top, err := unmarshalFirstJSONValue(data)
	if err != nil {
		return ""
	}
	return findLimaIP(top)
}

func unmarshalFirstJSONValue(data []byte) (any, error) {
	dec := json.NewDecoder(bytes.NewReader(data))
	var first any
	if err := dec.Decode(&first); err != nil {
		return nil, err
	}
	if list, ok := first.([]any); ok {
		if len(list) == 0 {
			return nil, fmt.Errorf("empty instance list")
		}
		return list[0], nil
	}
	return first, nil
}

func findLimaIP(v any) string {
	switch t := v.(type) {
	case map[string]any:
		for _, key := range []string{"networks", "Networks"} {
			if networks, ok := t[key].([]any); ok {
				for _, network := range networks {
					if ip := findLimaIP(network); ip != "" {
						return ip
					}
				}
			}
		}
		for _, key := range []string{"ip", "IP", "address", "Address", "ipAddress", "IPAddress"} {
			if value, ok := t[key].(string); ok {
				if ip := net.ParseIP(value); ip != nil && !ip.IsLoopback() {
					return value
				}
			}
		}
	case []any:
		for _, item := range t {
			if ip := findLimaIP(item); ip != "" {
				return ip
			}
		}
	}
	return ""
}

func prepareLimaVM(ctx context.Context, logger *logrus.Logger, opt *LocalOptions) (*limaVM, error) {
	vm, err := startLimaVM(ctx, logger, opt)
	if err != nil {
		return nil, err
	}

	if err := bootstrapLimaVM(ctx, logger, vm); err != nil {
		return nil, err
	}

	vm.ip, err = limaVMIP(ctx, logger, vm)
	if err != nil {
		return nil, err
	}
	logger.Infof("Lima VM %q is ready at %s", vm.instance, vm.ip)

	return vm, nil
}

func shellQuote(s string) string {
	return "'" + strings.ReplaceAll(s, "'", `'\''`) + "'"
}

// stageFile transfers a small file into the VM. Content is passed through
// base64 because `limactl copy` cannot handle paths containing a colon (the
// registry certs directory is named after the host:port registry address).
func (vm *limaVM) stageFile(ctx context.Context, localPath, remotePath string) error {
	data, err := os.ReadFile(localPath)
	if err != nil {
		return fmt.Errorf("failed to read %q for staging into the VM: %w", localPath, err)
	}
	encoded := base64.StdEncoding.EncodeToString(data)
	if out, err := vm.shell(ctx, "sh", "-c", fmt.Sprintf("echo %s | base64 -d > %s", encoded, shellQuote(remotePath))).CombinedOutput(); err != nil {
		return fmt.Errorf("failed to stage %q into the VM at %q: %w\n%s", localPath, remotePath, err, string(out))
	}
	return nil
}

// createKindCluster stages the kind config and the registry certs into the
// VM and creates the kind cluster inside it. The certs dir host path in the
// kind config refers to a VM-local path so the kind nodes can mount it.
func (vm *limaVM) createKindCluster(ctx context.Context, logger *logrus.Logger, opt *LocalOptions, kindConfigPath, certsRoot string) error {
	remoteCertsRoot := filepath.Join(vmRemoteDir, "containerd-certs.d")
	remoteKindConfig := filepath.Join(vmRemoteDir, "kind-config.yaml")

	if certsRoot != "" {
		remoteCertsDir := filepath.Join(remoteCertsRoot, opt.Registry)
		if out, err := vm.shell(ctx, "sh", "-c", "mkdir -p "+shellQuote(remoteCertsDir)).CombinedOutput(); err != nil {
			return fmt.Errorf("failed to prepare %q inside the VM: %w\n%s", remoteCertsDir, err, string(out))
		}
		if err := vm.stageFile(ctx, filepath.Join(certsRoot, opt.Registry, "hosts.toml"), filepath.Join(remoteCertsDir, "hosts.toml")); err != nil {
			return err
		}
	}
	if err := vm.stageFile(ctx, kindConfigPath, remoteKindConfig); err != nil {
		return err
	}

	// limactl shell sessions multiplex over an SSH connection established
	// before the docker group was granted, so docker access needs sg
	if out, err := vm.shell(ctx, "sh", "-c", "sg docker -c "+shellQuote("kind get clusters")).CombinedOutput(); err == nil && strings.Contains(strings.TrimSpace(string(out)), vm.cluster) {
		logger.Infof("Kind cluster %q already exists inside the VM, skipping creation...", vm.cluster)
	} else {
		logger.Infof("Creating kind cluster %q inside the VM (node image pull can take a while)…", vm.cluster)
		create := fmt.Sprintf("kind create cluster -n %s --config %s", vm.cluster, remoteKindConfig)
		if out, err := vm.shell(ctx, "sh", "-c", "sg docker -c "+shellQuote(create)).CombinedOutput(); err != nil {
			return fmt.Errorf("failed to create kind cluster %q inside the VM: %w\n%s", vm.cluster, err, string(out))
		}
	}

	return nil
}

// extractKubeconfig reads the kind kubeconfig from inside the VM, rewrites
// the apiserver address to the loopback address forwarded by lima and writes
// it to destPath on the host.
func (vm *limaVM) extractKubeconfig(ctx context.Context, logger *logrus.Logger, destPath string) error {
	var out []byte
	var err error
	getKubeconfig := fmt.Sprintf("kind get kubeconfig --name %s", vm.cluster)
	if out, err = vm.shell(ctx, "sh", "-c", "sg docker -c "+shellQuote(getKubeconfig)).Output(); err != nil {
		return fmt.Errorf("failed to get the kind kubeconfig from inside the VM: %w", err)
	}

	kubeconfig := rewriteKubeconfigServer(string(out), fmt.Sprintf("https://127.0.0.1:%d", vmKindAPIserverPort))
	if err := os.WriteFile(destPath, []byte(kubeconfig), 0600); err != nil {
		return fmt.Errorf("failed to write the kind kubeconfig: %w", err)
	}
	logger.Infof("Kind kubeconfig written to %s (apiserver via lima port-forward 127.0.0.1:%d)", destPath, vmKindAPIserverPort)

	return nil
}

func rewriteKubeconfigServer(kubeconfig, server string) string {
	return regexp.MustCompile(`(server:) https://[^:\s]+:[0-9]+`).ReplaceAllString(kubeconfig, "${1} "+server)
}
